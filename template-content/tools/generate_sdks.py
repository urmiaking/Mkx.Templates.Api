"""Deterministic, fail-closed API SDK generator for the supported OpenAPI subset.

No npm/java/OpenAPI online service required to generate. Reject unknown schemas,
missing security requirements and unknown ref kinds instead of silently producing
unsafe clients. Output MUST be updated and checked when Swagger changes.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "openapi/v1.json"
OUT = {
    "typescript/src/models.ts": None,
    "typescript/src/client.ts": None,
    "dart/lib/src/models.dart": None,
    "dart/lib/src/client.dart": None,
}
SECURITY = {"LocalJwt", "ExternalOidc", "OpaqueToken", "ApiKey"}
HTTP = {"get", "post", "put", "patch", "delete"}
TOKEN_OPERATIONS = {"Auth_Login", "Auth_Refresh", "Passkeys_LoginComplete"}


def ref_name(schema):
    value = schema.get("$ref")
    if not value or not value.startswith("#/components/schemas/"):
        raise ValueError(f"Unknown model reference: {schema}")
    return value.rsplit("/", 1)[-1]


def type_of(schema, lang):
    if "$ref" in schema:
        return ref_name(schema)
    kind = schema.get("type")
    if kind == "array":
        items = schema.get("items")
        if not isinstance(items, dict):
            raise ValueError(f"Array must declare item schema: {schema}")
        typ = type_of(items, lang)
        return f"List<{typ}>" if lang == "dart" else f"Array<{typ}>"
    if kind == "string":
        return "String" if lang == "dart" else "string"
    if kind == "integer" or kind == "number":
        return ("int" if kind == "integer" else "double") if lang == "dart" else "number"
    if kind == "boolean":
        return "bool" if lang == "dart" else "boolean"
    if kind == "object":
        props = schema.get("additionalProperties")
        if props is True or props is None:
            return "Map<String, dynamic>" if lang == "dart" else "Record<string, unknown>"
        if isinstance(props, dict):
            v = type_of(props, lang)
            return f"Map<String, {v}>" if lang == "dart" else f"Record<string, {v}>"
    raise ValueError(f"Unsupported OpenAPI type, cannot generate safely: {schema}")


def is_null(schema):
    return bool(schema.get("nullable"))


def ts_models(models):
    chunks = ["// GENERATED by tools/generate_sdks.py from openapi/v1.json; DO NOT EDIT.", ""]
    for name, schema in sorted(models.items()):
        if schema.get("type") != "object":
            raise ValueError(f"Unsupported model type for {name}: {schema}")
        chunks.append(f"export interface {name} {{")
        for key, prop in sorted(schema.get("properties", {}).items()):
            typ = type_of(prop, "ts")
            optional = "?" if is_null(prop) or key not in schema.get("required", []) else ""
            if is_null(prop):
                typ += " | null"
            chunks.append(f"  {json.dumps(key)}{optional}: {typ};")
        chunks.append("}")
        chunks.append("")
    return "\n".join(chunks).rstrip() + "\n"


def dart_decode(schema, expression):
    nullable = is_null(schema)
    base = dict(schema)
    base.pop("nullable", None)
    if "$ref" in base:
        name = ref_name(base)
        parse = f"{name}.fromJson({expression} as Map<String, dynamic>)"
    elif base.get("type") == "array":
        item = base["items"]
        expr = dart_decode(item, "element")
        parse = f"({expression} as List<dynamic>).map((element) => {expr}).toList()"
    elif base.get("type") == "object":
        parse = f"({expression} as Map<String, dynamic>)"
    else:
        parse = f"{expression} as {type_of(base, 'dart')}"
    return f"({expression} == null ? null : {parse})" if nullable else parse


def dart_encode(schema, expression):
    if "$ref" in schema:
        return f"{expression}.toJson()"
    if schema.get("type") == "array":
        item = schema["items"]
        if "$ref" in item:
            return f"{expression}.map((element) => element.toJson()).toList()"
    return expression


def dart_models(models):
    chunks = ["// GENERATED by tools/generate_sdks.py from openapi/v1.json; DO NOT EDIT.", ""]
    for name, schema in sorted(models.items()):
        if schema.get("type") != "object":
            raise ValueError(f"Unsupported model type for {name}")
        fields = sorted(schema.get("properties", {}).items())
        chunks += [f"class {name} {{"]
        for key, prop in fields:
            typ = type_of(prop, "dart")
            if is_null(prop):
                typ += "?"
            chunks.append(f"  final {typ} {key};")
        chunks.append("")
        constructor = ", ".join(
            ("this." if is_null(prop) else "required this.") + key for key, prop in fields
        )
        chunks.append(f"  const {name}({{{constructor}}});" if fields else f"  const {name}();")
        chunks.append(f"  factory {name}.fromJson(Map<String, dynamic> json) => {name}(")
        for key, prop in fields:
            chunks.append(f"    {key}: {dart_decode(prop, 'json[' + json.dumps(key) + ']')},")
        chunks.append("  );")
        chunks.append("  Map<String, dynamic> toJson() => {")
        for key, prop in fields:
            expression = dart_encode(prop, key)
            if is_null(prop):
                # Use null-safe collection entry and avoid JSON with null properties.
                chunks.append(f"    if ({key} != null) {json.dumps(key)}: {expression if expression == key else expression.replace(key, key + '!')},")
            else:
                chunks.append(f"    {json.dumps(key)}: {expression},")
        chunks += ["  };", "}", ""]
    return "\n".join(chunks).rstrip() + "\n"


def operation_schema(operation, request=False):
    content = (operation.get("requestBody", {}) if request else
               next((v for k, v in sorted(operation["responses"].items())
                     if k in ("200", "201", "202", "204")), {})).get("content", {})
    mime = content.get("application/json")
    if mime is None:
        # Non-JSON response types are not assumed typed unless a schema exists.
        return None
    return mime.get("schema")


def operations(doc):
    found = []
    ids = set()
    for path, routes in sorted(doc["paths"].items()):
        for method, op in sorted(routes.items()):
            if method not in HTTP:
                continue
            opid = op["operationId"]
            if opid in ids or not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", opid):
                raise ValueError(f"Duplicate or malformed operationId: {opid}")
            ids.add(opid)
            declared = op.get("security", [])
            if len(declared) > 1:
                raise ValueError(f"Multiple alternative security requirements unsupported: {opid}")
            if declared and (len(declared[0]) != 1 or
                             next(iter(declared[0])) not in SECURITY):
                raise ValueError(f"Unknown security scheme: {opid} = {declared}")
            scheme = next(iter(declared[0])) if declared else None
            args = op.get("parameters", [])
            if any(arg.get("in") not in ("path", "query") for arg in args):
                raise ValueError(f"Unsupported parameter kind on {opid}")
            data = dict(id=opid, name=opid.split("_")[0][:1].lower() +
                        opid.split("_")[0][1:] + opid.split("_", 1)[1],
                        path=path, method=method.upper(), security=scheme,
                        params=args,
                        body=operation_schema(op, True), response=operation_schema(op))
            if data["body"] is not None and not isinstance(data["body"], dict):
                raise ValueError(f"Invalid requestBody for {opid}")
            found.append(data)
    if not found or len(found) < 20:
        raise ValueError("Incomplete OpenAPI contract")
    return found


def ts_client(ops):
    chunks = [
        "// GENERATED by tools/generate_sdks.py from openapi/v1.json; DO NOT EDIT.",
        'import { ApiTransport } from "./transport.js";',
        'import type * as models from "./models.js";',
        "",
        "export class MkxApiClient extends ApiTransport {"
    ]
    for op in ops:
        params = [p for p in op["params"] if p["in"] == "path"]
        query = [p for p in op["params"] if p["in"] == "query"]
        variables = []
        for arg in params + query:
            typ = type_of(arg["schema"], "ts")
            optional = "?" if not arg.get("required", False) else ""
            variables.append(f"{arg['name']}{optional}: {typ}")
        if op["body"] is not None:
            typ = type_of(op["body"], "ts")
            if "$ref" in op["body"]:
                typ = "models." + typ
            variables.append(f"body: {typ}")
        # Query params are optional but TS does not allow required arguments
        # after optional ones; body needs to be first.
        if op["body"] is not None and query:
            variables.insert(0, variables.pop())
        schema = op["response"]
        ret = type_of(schema, "ts") if schema else "void"
        if schema and "$ref" in schema:
            ret = "models." + ret
        elif schema and schema.get("type") == "array" and "$ref" in schema.get("items", {}):
            ret = f"Array<models.{ref_name(schema['items'])}>"
        path_expr = json.dumps(op["path"])
        for param in params:
            path_expr += f".replace({json.dumps('{' + param['name'] + '}')}, encodeURIComponent({param['name']}))"
        query_expr = ("{ " + ", ".join(p["name"] for p in query) + " }") if query else "undefined"
        body_expr = "body" if op["body"] is not None else "undefined"
        chunks.append(f"  async {op['name']}({', '.join(variables)}): Promise<{ret}> {{")
        chunks.append(f"    const result = await this.request<{ret}>({json.dumps(op['method'])}, {path_expr}, {json.dumps(op['security'])}, {body_expr}, {query_expr});")
        if op["id"] in TOKEN_OPERATIONS:
            chunks.append("    if (!result?.accessToken || !result?.refreshToken) throw new Error('Token response malformed');")
            chunks.append("    await this.persistTokens({ accessToken: result.accessToken, refreshToken: result.refreshToken });")
        chunks.append("    return result;")
        chunks.append("  }")
        chunks.append("")
    return "\n".join(chunks + ["}", ""])


def dart_client(ops):
    chunks = [
        "// GENERATED by tools/generate_sdks.py from openapi/v1.json; DO NOT EDIT.",
        "import 'models.dart';",
        "import 'transport.dart';",
        "",
        "class MkxApiClient extends ApiTransport {",
        "  MkxApiClient({required super.baseUrl, super.client, super.sessionStore,",
        "    super.externalAccessToken, super.opaqueAccessToken, super.apiKey});",
        ""
    ]
    for op in ops:
        params = [p for p in op["params"] if p["in"] == "path"]
        query = [p for p in op["params"] if p["in"] == "query"]
        arg_list = []
        for arg in params:
            arg_list.append(type_of(arg["schema"], "dart") + " " + arg["name"])
        if op["body"] is not None:
            arg_list.append(type_of(op["body"], "dart") + " body")
        if query:
            arg_list.append("{" + ", ".join(type_of(p["schema"], "dart") + "? " + p["name"] for p in query) + "}")
        response_schema = op["response"]
        ret = type_of(response_schema, "dart") if response_schema else "void"
        chunks.append(f"  Future<{ret}> {op['name']}({', '.join(arg_list)}) async {{")
        chunks.append(f"    var path = {json.dumps(op['path'])};")
        for param in params:
            chunks.append("    path = path.replaceFirst(" + json.dumps("{" + param["name"] + "}") +
                          ", Uri.encodeComponent(" + param["name"] + "));")
        query_text = ("{ " + ", ".join(json.dumps(p["name"]) + ": " +
                      p["name"] + "?.toString()" for p in query) + " }") if query else "null"
        body_text = "body.toJson()" if op["body"] is not None and "$ref" in op["body"] else "null"
        prefix = "final json = " if response_schema is not None else ""
        chunks.append(f"    {prefix}await request({json.dumps(op['method'])}, path, {json.dumps(op['security'])}, body: {body_text}, query: {query_text});")
        if response_schema is not None:
            chunks.append("    final result = " + dart_decode(response_schema, "json") + ";")
            if op["id"] in TOKEN_OPERATIONS:
                chunks.append("    if (result.accessToken == null || result.refreshToken == null) throw const FormatException('Missing token response');")
                chunks.append("    await persistTokens(result.accessToken!, result.refreshToken!);")
            chunks.append("    return result;")
        chunks += ["  }", ""]
    return "\n".join(chunks + ["}", ""])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    doc = json.loads(SPEC.read_text(encoding="utf-8"))
    models = doc["components"]["schemas"]
    ops = operations(doc)
    targets = {
        "typescript/src/models.ts": ts_models(models),
        "typescript/src/client.ts": ts_client(ops),
        "dart/lib/src/models.dart": dart_models(models),
        "dart/lib/src/client.dart": dart_client(ops)
    }
    for name, content in targets.items():
        file = ROOT / "clients" / name
        if args.check:
            if not file.exists() or file.read_text(encoding="utf-8-sig") != content:
                sys.exit(f"SDK drift in {name}; run python tools/generate_sdks.py")
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content, encoding="utf-8")
    print(f"SDKs {'verified' if args.check else 'generated'}: {len(ops)} operations, {len(models)} models, TypeScript and Dart")


if __name__ == "__main__":
    main()
